from flask_restx import fields, Model
from app.schemas.base_schema import BaseSchema

class ProjectSchema(BaseSchema):
    @classmethod
    def get_schema(cls, namespace: Model):
        return namespace.model("ProjectResponse", {
            **BaseSchema.get_schema(namespace),
            "data": fields.Nested(namespace.model("Project", {
                "id": fields.Integer,
                "name": fields.String,
                "location": fields.String,
                "type": fields.String(description="ProjectType Enum"),
                "duration": fields.String,
                "start_date": fields.String(description="ISO 8601 Date"),
                "end_date": fields.String(description="ISO 8601 Date"),
                "code": fields.String,
                "payment_type": fields.String(description="PaymentType Enum"),
                "description": fields.String,
                "current_stages": fields.String(description="Stages Enum"),
                "contact_id": fields.Integer,
                "partner_id": fields.Integer,
                "invoice_id": fields.Integer,
                "lead_id": fields.Integer,
                "meta": fields.Nested(namespace.model("Meta", {
                    "created_at": fields.String(description="ISO 8601 Date"),
                    "updated_at": fields.String(description="ISO 8601 Date"),
                    "created_by": fields.Integer,
                    "updated_by": fields.Integer,
                })),
            }))
        })
    
    @classmethod
    def post_schema(cls, namespace: Model):
        return namespace.model("ProjectPostRequest", {
            "name": fields.String(required=True),
            "location": fields.String(required=True),
            "type": fields.String(required=True, description="Other, BECdex Certification, CBEc Training Course, Maritime Professional"),
            "duration": fields.String(required=True),
            "start_date": fields.String(required=True, description="YYYY-MM-DD"),
            "end_date": fields.String(description="YYYY-MM-DD"),
            "code": fields.String(required=False, description="Auto-generated by system (MMN-DDMMYY-lead_id)"),
            "payment_type": fields.String(required=True, description="Cash, Cashless, Digital/Electronic"),
            "description": fields.String(required=True),
            "current_stages": fields.String(required=True, description="Concept, Planning, Execution, Monitoring, Closing"),
            "contact_id": fields.Integer(required=False, allow_null=True),
            "partner_id": fields.Integer(required=False, allow_null=True),
            "invoice_id": fields.Integer(required=False, allow_null=True),
            "lead_id": fields.Integer(required=False, allow_null=True),
        })

    @classmethod
    def filter_schema(cls, namespace: Model):
        """Schema untuk Request Body Search & Filter Project"""
        return namespace.model("ProjectFilterRequest", {
            "page_size": fields.Integer(required=True, default=25),
            "page_number": fields.Integer(required=True, default=1),
            "sort_by": fields.String(required=True, default="id"),
            "sort_order": fields.String(required=True, default="DESC"),
            "search": fields.String(description="Search by Name, Code, Location, or Description"),
            "type": fields.String(description="Filter by Project Type"),
            "current_stages": fields.String(description="Filter by Current Stage"),
            "start_date": fields.String(description="Filter start date (YYYY-MM-DD)"),
            "end_date": fields.String(description="Filter end date (YYYY-MM-DD)")
        }, ordered=True)

    @classmethod
    def filter_response_schema(cls, namespace: Model):
        """Schema untuk Response List Project dengan Pagination"""
        project_item = namespace.model("ProjectFilterItem", {
            "id": fields.Integer,
            "name": fields.String,
            "code": fields.String,
            "type": fields.String,
            "current_stages": fields.String,
            "start_date": fields.String,
            "end_date": fields.String,
            "partner_name": fields.String,
            "contact_name": fields.String,
            "meta": fields.Nested(namespace.model("Meta", {
                "created_at": fields.String(description="ISO 8601 Date"),
                "updated_at": fields.String(description="ISO 8601 Date"),
                "created_by": fields.Integer,
                "updated_by": fields.Integer,
            })),
        }, ordered=True)

        pagination = namespace.model("ProjectPaginationInfo", {
            "current_page": fields.Integer,
            "page_size": fields.Integer,
            "total_pages": fields.Integer,
            "total_items": fields.Integer
        }, ordered=True)

        return namespace.model("ProjectFilterResponse", {
            "message": fields.String(default="Success"),
            "code": fields.Integer(default=200),
            "status": fields.String(default="success"),
            "data": fields.Nested(namespace.model("ProjectFilterData", {
                "list": fields.List(fields.Nested(project_item)),
                "pagination": fields.Nested(pagination)
            }))
        }, ordered=True)